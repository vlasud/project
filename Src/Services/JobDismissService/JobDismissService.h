#pragma once

#include "Services/IService.h"
#include "player.hpp"
#include <functional>
#include <string>
#include <vector>

// Увольнение с работы «откуда угодно» — бизнес-сервис (НЕ Core: про работы Core знать
// не должен). Отвечает на два вопроса: какой работой игрок занят прямо сейчас и как
// эту смену прервать.
//
// Нужен ради ОДНОЙ универсальной точки выхода (/stopjob, привод — JobDismissSystem):
// иначе уволиться можно только у пикапа своей работы, то есть уехав на маршрут — уже
// никак. Сервис держит не логику увольнения, а ССЫЛКУ на неё: увольняет по-прежнему
// сама работа своим обработчиком (кошелёк, транспорт, очередь, лок, пара) — второй
// ветки увольнения в проекте не появляется.
//
// САМОРЕГИСТРАЦИЯ (как у типов InventoryService): каждая работа зовёт registerJob в
// конструкторе своей системы. Новая работа — одна строка регистрации, ни сервис, ни
// /stopjob не правятся. О самих работах сервис ничего не знает: имя и предупреждение —
// просто строки от держателя, «занят ли» и «уволить» — его же колбэки.
//
// Работы взаимоисключающи (общий NavigationLockService), поэтому активной может быть
// только одна; при нескольких совпадениях берётся первая зарегистрированная.
// Событийный сервис: обращения только по команде игрока, per-tick работы нет.
class JobDismissService final : public IService
{
  public:
    // Занят ли игрок этой работой прямо сейчас (по правде работы, не по клиенту).
    using WorkingPredicate = std::function<bool(int playerId)>;
    // Уволить игрока с этой работы. Зовётся ТОЛЬКО когда predicate уже сказал «занят»;
    // работа сама решает, что это значит (выход из очереди / конец смены).
    using DismissHandler = std::function<void(IPlayer &player)>;

    struct Job
    {
        std::string name;    // utf-8, для игрока: «водитель автобуса»
        std::string warning; // utf-8: что игрок теряет, уволившись
        WorkingPredicate isWorking;
        DismissHandler dismiss;
    };

    // Зарегистрировать работу как увольняемую. Вызывается в конструкторе системы
    // работы; пустые колбэки игнорируются (регистрация без них бессмысленна).
    void registerJob(std::string name, std::string warning, WorkingPredicate isWorking, DismissHandler dismiss);

    // Работа, которой игрок занят сейчас, либо nullptr. Указатель стабилен: список
    // наполняется только на старте (конструкторы систем), в игре не меняется.
    const Job *currentJob(int playerId) const;

  private:
    std::vector<Job> m_jobs;
};
