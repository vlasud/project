#pragma once

#include "Services/IService.h"
#include "types.hpp"
#include <vector>

// Каталог именованных мест мира — бизнес-сервис (НЕ Core). Одна таблица «название ->
// координаты», из которой строятся ВСЕ списки мест в игре: /gps, /tp и выбор точки
// назначения в такси.
//
// Вынесен из GpsSystem, когда потребителей стало двое: адрес больницы или депо не
// должен existовать в двух местах — добавили точку сюда, и она появилась во всех
// списках сразу.
//
// Здесь ТОЛЬКО статика мира. Пер-игроковые цели («мой дом», «моя организация»)
// каталогом не являются: они резолвятся от конкретного игрока и живут у того, кто
// умеет их резолвить (GpsSystem), — иначе сервису пришлось бы знать про дома и
// фракции.
//
// Наполняется в конструкторе и в игре не меняется: ссылка на список стабильна,
// индекс строки диалога однозначно адресует место.
class PlaceCatalogService final : public IService
{
  public:
    struct Place
    {
        const char *name; // utf-8
        Vector3 position;
    };

    PlaceCatalogService();

    const std::vector<Place> &places() const;

  private:
    std::vector<Place> m_places;
};
