struct Info
{
    float maxDamage; // максимум урона за один хит
    float range;     // дальность, метры (до допусков на лаг)
    // Минимальный интервал между хитами (rate limit). Используется только для
    // НЕпулевого оружия (мили, гранаты, огнемёт, спрей): для пулевого темп берётся
    // из PlayerWeaponService::minShotInterval — единый источник по реальному
    // shootTime из SDK, чтобы два лимита не расходились.
    int minIntervalMs;
};

